      <p>
        I'm a Hamburg-based <span class="text-line-through">independent open source software developer</span>
        <span class="text-line-through">tortured artist and creative technologist</span> mostly eukaryotic multicellular
        form of life operating at the intersection of language, systems thinking, and written as well as visual art.<br>
        <br>
        In technology, I specialise in crafting high-quality software for UNIX and Windows platforms, with a focus on
        aesthetic engineering - creating expressive code and technical documentation that is as readable and composable as
        a well-woven poem. I take a <em>failure-oriented</em> approach in engineering, designing systems with primary
        consideration for how and when they fail as well as how to adequately address failure. I am equally open to exploring
        novel pathways and perspectives, particularly those that expand our modes of expression and induce the epistemic
        collapse of questions in need of unasking. I highly value methodical and structural approaches grounded in sound
        notions as well as calling the same into question when it is contradicted by empirical evidence, no matter how
        conventionally established the former or poor in data quality the latter may be.<br>
        <br>
        I have contributed to a <a href="/<?php echo $inc_lang ?>/projects">number of open source projects</a> and continue to
        maintain a <a href="https://github.com/lalbornoz/">GitHub</a>. My Curriculum Vitae is available on this website both as a
        <a href="/assets/Curriculum%20Vitae%20(English).pdf">PDF</a> and as a <a href="/assets/CurriculumVitae.tex">LaTeX</a>
        source file.<br>
        <br>
        I have a passionate, lifelong interest in languages, nurtured by the multilingual and multicultural environment that I
        grew up in, beginning with my native <em>Spanish (Chilean/Andalusian dialect)</em> and <em>German (Northern Germany/
        Hamburg dialect)</em> as well as <em>English (British English)</em> at CEFR level C1 according to personal judgment
        and, as a classical language, <em>Classical Arabic</em> and a smattering of dialects of <em>Spoken Arabic</em>, garnished
        with undertones of <em>Akkadian</em> and <em>Persian</em>.<br>
        <br>
        In creativity, I am drawn to weaving higher-order patterns from matters of little in the way of connection and often
        much in the way of contradiction, applying my tools of the trade of negation and dissociation to draw from the fields
        of the treasury of the unseen, from Old Mesopotamia, Classical Arabic literature, mysticism, magical realism to gender
        identity, non-dualism, <a href="/<?php echo $inc_lang ?>/etc">kade</a>, neutrinos, clinical psychology and psychiatry,
        and the indelibly indelicate flavour of my puzzlingly continuing existence. In literature, I greatly prefer the expression
        and exploration of <em>subjectivity of experience</em> over the mere replication of ostensible objectivity, often in the
        garb of an unwaveringly resolute reality that by the threshold of the merest insignificance unveils a world unseen,
        wherein liberation is obtained from the coexistence, not contradiction, of opposites, if one should find oneself willing
        to abandon undue attachment and become extinguished like a silent flame within the Pale. Oftentimes, that which cannot
        be named has greater importance than what can be and that merely naming a thing may destroy that very thing.<br>
        <br>
        I have a general interest in systems and dynamic processes that, much like the stillness of a garden perturbed by the
        gradients and curves of Classical Persian music, unfold with dazzling dimensionality, laden with recurrent loops which bear
        state networks distributed in captivating patterns, especially those found in biology in general and endocrinology in
        particular as well as whatever a long walk or indulging in a film or musical fragment 6 seconds in duration may yield
        when serving as the means of phenomenological archaeology.<br>
        <br>
        In music, I am fascinated by musical pieces that express non-linear motion - <em>travel without moving</em> - through
        recurrent temporal geometry: feeding overlapping and desynchronised, yet continually attracting, converging, and dissociating,
        mutually interacting systems back into themselves, generating self-modulation that induces phase shifts towards patterns of
        ever-escalating complexity, all while unfolding with profound narrative structure. The rare instances of such music, be it
        the alternate version of <em>Somewhere in Space</em> by <em>Sun Ra</em> with <em>Art Jenkins</em> playing his inverted ram's
        horn, the <em>Jazzpunk Theme</em>, <em>Lai Se</em> by <em>Fela Kuti and His Koola Lobitos</em>, or Classical Persian Music,
        may very well, as far as I am concerned, constitute the auditory expression of proteins folding into an ordered 3-dimensional
        structure through a mesmerising quantity of mutual interactions from a humble string of amino acids or the very sound of the
        Pale itself that may only be heard when one ceases to hear. Music emerges from the emptiness between notes.<br>
        <br>
